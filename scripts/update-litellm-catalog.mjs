#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const source = "https://raw.githubusercontent.com/BerriAI/litellm/refs/heads/main/model_prices_and_context_window.json";
const modelsSource = "https://models.litellm.ai/";
const snapshotDate = process.env.CATALOG_SNAPSHOT_DATE || new Date().toISOString().slice(0, 10);
const output = resolve("src/litellm-catalog.ts");

const number = (value) => typeof value === "number" && Number.isFinite(value) ? value : undefined;
const bool = (value) => value === true;
const list = (value) => Array.isArray(value) ? value.filter((item) => typeof item === "string").sort() : [];
const includesAny = (value, terms) => terms.some((term) => String(value || "").toLowerCase().includes(term));

const response = await fetch(source, { headers: { "Cache-Control": "no-cache", Accept: "application/json" } });
if (!response.ok) throw new Error(`LiteLLM catalog returned HTTP ${response.status}.`);
const raw = await response.json();
const requestedModels = new Set((process.env.LITELLM_MODELS || "gpt-6.1-sol,gpt-6-astra,gpt-6-sol,gpt-6-luna,gpt-5.6,gpt-4.1,claude-sonnet-5")
  .split(",").map((model) => model.trim().toLowerCase()).filter(Boolean));
const entries = Object.entries(raw).filter(([model]) => requestedModels.has(model.toLowerCase())).map(([model, value]) => {
  const item = value && typeof value === "object" ? value : {};
  const modalities = list(item.modalities || item.input_modalities);
  const outputModalities = list(item.output_modalities);
  const endpoints = [];
  if (item.supports_chat_completions !== false) endpoints.push("chat_completions");
  if (item.supports_responses_api === true || item.supports_responses === true) endpoints.push("responses");
  const reasoning = bool(item.supports_reasoning) || includesAny(model, ["o1", "o3", "o4", "gpt-5", "gpt-6", "claude"]);
  return {
    model,
    provider: String(item.litellm_provider || item.provider || "unknown"),
    sourceDate: snapshotDate,
    ...(number(item.max_input_tokens || item.max_tokens) ? { maxInputTokens: number(item.max_input_tokens || item.max_tokens) } : {}),
    ...(number(item.max_output_tokens) ? { maxOutputTokens: number(item.max_output_tokens) } : {}),
    endpoints: endpoints.length ? endpoints : ["chat_completions"],
    inputModalities: modalities,
    outputModalities,
    supportsFunctionCalling: bool(item.supports_function_calling),
    supportsParallelFunctionCalling: bool(item.supports_parallel_function_calling),
    supportsReasoning: reasoning,
    reasoningEfforts: list(item.reasoning_efforts),
    supportsNoneReasoningEffort: list(item.reasoning_efforts).includes("none"),
    supportsStructuredOutput: bool(item.supports_structured_output),
    toolChoice: list(item.tool_choice),
    vision: includesAny(modalities, ["image", "vision"]),
    pdf: includesAny(modalities, ["pdf"]),
    audio: includesAny(modalities, ["audio"]),
    promptCaching: bool(item.supports_prompt_caching),
    systemMessages: item.supports_system_messages !== false,
    webSearch: bool(item.supports_web_search),
    computerUse: bool(item.supports_computer_use),
    ...(number(item.input_cost_per_token) ? { inputPricePerMillion: item.input_cost_per_token * 1_000_000 } : {}),
    ...(number(item.output_cost_per_token) ? { outputPricePerMillion: item.output_cost_per_token * 1_000_000 } : {}),
    ...(typeof item.deprecation_date === "string" ? { deprecationDate: item.deprecation_date } : {})
  };
}).filter((item) => item.model && item.model.length < 180).sort((a, b) => a.model.localeCompare(b.model));

const generated = `/** Generated by scripts/update-litellm-catalog.mjs. Source: ${source} (model aliases: ${modelsSource}). Snapshot: ${snapshotDate}. */\nexport type LiteLlmCatalogMetadata = { model: string; provider: string; sourceDate: string; maxInputTokens?: number; maxOutputTokens?: number; endpoints: Array<"chat_completions" | "responses">; inputModalities: string[]; outputModalities: string[]; supportsFunctionCalling: boolean; supportsParallelFunctionCalling: boolean; supportsReasoning: boolean; reasoningEfforts: string[]; supportsNoneReasoningEffort: boolean; supportsStructuredOutput: boolean; toolChoice: string[]; vision: boolean; pdf: boolean; audio: boolean; promptCaching: boolean; systemMessages: boolean; webSearch: boolean; computerUse: boolean; inputPricePerMillion?: number; outputPricePerMillion?: number; deprecationDate?: string; };\nexport const LITELLM_CATALOG_SOURCE = ${JSON.stringify(source)};\nexport const LITELLM_CATALOG_MODELS_SOURCE = ${JSON.stringify(modelsSource)};\nexport const LITELLM_CATALOG_SNAPSHOT_DATE = ${JSON.stringify(snapshotDate)};\nexport const LITELLM_MODEL_CATALOG: Record<string, LiteLlmCatalogMetadata> = ${JSON.stringify(Object.fromEntries(entries), null, 2)};\nexport function liteLlmCatalogMetadata(model: string, provider = "litellm"): LiteLlmCatalogMetadata | undefined { const found = LITELLM_MODEL_CATALOG[model.trim().toLowerCase()]; return found && (provider === "litellm" || found.provider === provider) ? found : undefined; }\n`;
await writeFile(output, generated, "utf8");
console.log(`Wrote ${entries.length} LiteLLM model records to ${output}`);
